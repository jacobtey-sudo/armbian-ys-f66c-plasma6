#!/usr/bin/env bash
#
# Write the runtime pin file read by overlay scripts on the device.
#
# Usage:
#   ./scripts/gen-runtime-pins.sh /etc/ys-f66c/versions.env
#
# Values come from config/versions.env. build.sh writes the file into the
# overlay before the image build; install-overlay.sh writes it to /etc.

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../config/versions.env
source "${REPO_DIR}/config/versions.env"

OUT="${1:?usage: $0 <output-file>}"

: "${FLCLASH_VERSION:?FLCLASH_VERSION is not set in config/versions.env}"
: "${FLCLASH_SHA256:?FLCLASH_SHA256 is not set in config/versions.env}"

mkdir -p "$(dirname "${OUT}")"

{
	echo "# Generated by scripts/gen-runtime-pins.sh from config/versions.env."
	echo "# Do not edit on the device; the next build or overlay install overwrites it."
	echo "FLCLASH_VERSION=\"${FLCLASH_VERSION}\""
	echo "FLCLASH_SHA256=\"${FLCLASH_SHA256}\""
} > "${OUT}"
